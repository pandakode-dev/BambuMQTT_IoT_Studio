package com.pandakode.bambumqtt.utils

import com.pandakode.bambumqtt.model.IotWidgetItem
import com.pandakode.bambumqtt.model.WidgetType
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.ByteArrayOutputStream
import java.net.InetSocketAddress
import java.net.Socket

object MqttNativeEngine {

    // Menguji Koneksi & Mengirim Paket MQTT v3.1.1 PUBLISH Murni via TCP Socket (Port 1883)
    suspend fun publishMqttPacketTcp(
        brokerHost: String,
        brokerPort: Int,
        clientId: String,
        topic: String,
        payload: String
    ): Result<String> = withContext(Dispatchers.IO) {
        try {
            val socket = Socket()
            socket.connect(InetSocketAddress(brokerHost, brokerPort), 3500)
            socket.soTimeout = 3500
            val out = socket.getOutputStream()
            val inp = socket.getInputStream()

            // 1. Rakit Paket MQTT CONNECT (0x10)
            val connectPacket = buildConnectPacket(clientId)
            out.write(connectPacket)
            out.flush()

            // Baca Balasan CONNACK (4 byte: 0x20, 0x02, 0x00, 0x00)
            val connAck = ByteArray(4)
            val readLen = inp.read(connAck)
            if (readLen < 4 || connAck[0] != 0x20.toByte() || connAck[3] != 0x00.toByte()) {
                socket.close()
                return@withContext Result.failure(Exception("Broker menolak CONNACK"))
            }

            // 2. Rakit Paket MQTT PUBLISH QoS 0 (0x30)
            val publishPacket = buildPublishPacket(topic, payload)
            out.write(publishPacket)
            out.flush()

            socket.close()
            Result.success("Terkirim ke $brokerHost:$brokerPort [$topic] -> $payload")
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    private fun buildConnectPacket(clientId: String): ByteArray {
        val varHeaderAndPayload = ByteArrayOutputStream()
        // Protocol Name "MQTT"
        writeMqttString(varHeaderAndPayload, "MQTT")
        // Protocol Level 4 (v3.1.1)
        varHeaderAndPayload.write(0x04)
        // Connect Flags: Clean Session (0x02)
        varHeaderAndPayload.write(0x02)
        // Keep Alive (60 seconds)
        varHeaderAndPayload.write(0x00)
        varHeaderAndPayload.write(0x3C)
        // Payload: Client ID
        writeMqttString(varHeaderAndPayload, clientId)

        val bodyBytes = varHeaderAndPayload.toByteArray()
        val fullPacket = ByteArrayOutputStream()
        fullPacket.write(0x10) // CONNECT Fixed Header
        writeRemainingLength(fullPacket, bodyBytes.size)
        fullPacket.write(bodyBytes)
        return fullPacket.toByteArray()
    }

    private fun buildPublishPacket(topic: String, message: String): ByteArray {
        val body = ByteArrayOutputStream()
        writeMqttString(body, topic)
        body.write(message.toByteArray(Charsets.UTF_8))

        val bodyBytes = body.toByteArray()
        val fullPacket = ByteArrayOutputStream()
        fullPacket.write(0x30) // PUBLISH QoS 0
        writeRemainingLength(fullPacket, bodyBytes.size)
        fullPacket.write(bodyBytes)
        return fullPacket.toByteArray()
    }

    private fun writeMqttString(out: ByteArrayOutputStream, str: String) {
        val bytes = str.toByteArray(Charsets.UTF_8)
        out.write((bytes.size ushr 8) and 0xFF)
        out.write(bytes.size and 0xFF)
        out.write(bytes)
    }

    private fun writeRemainingLength(out: ByteArrayOutputStream, length: Int) {
        var x = length
        do {
            var encodedByte = x % 128
            x /= 128
            if (x > 0) encodedByte = encodedByte or 128
            out.write(encodedByte)
        } while (x > 0)
    }

    // FITUR KILLER: Generator Otomatis Sketch Arduino IDE / ESP32 (.ino)
    fun generateEsp32ArduinoSketch(
        brokerIp: String,
        brokerPort: Int,
        widgets: List<IotWidgetItem>
    ): String {
        val sb = StringBuilder()
        sb.append("// ==========================================================\n")
        sb.append("// AUTO-GENERATED BY BAMBUMQTT IOT STUDIO (PANDAKODE)\n")
        sb.append("// Author : Muhammad Saputra (Pekanbaru, Riau)\n")
        sb.append("// Target : ESP32 / ESP8266 (Arduino IDE + PubSubClient)\n")
        sb.append("// ==========================================================\n\n")
        sb.append("#include <WiFi.h>\n")
        sb.append("#include <PubSubClient.h>\n\n")
        sb.append("const char* ssid = \"NAMA_WIFI_ANDA\";\n")
        sb.append("const char* password = \"PASSWORD_WIFI_ANDA\";\n")
        sb.append("const char* mqtt_server = \"$brokerIp\";\n")
        sb.append("const int mqtt_port = $brokerPort;\n\n")

        sb.append("// Definisi Pin GPIO dari Widget BambuMQTT\n")
        widgets.forEach { w ->
            val safeName = w.title.uppercase().replace(" ", "_").replace("[^A-Z0-9_]".toRegex(), "")
            sb.append("#define PIN_$safeName ${w.gpioPin} // Topic: ${w.topic}\n")
        }

        sb.append("\nWiFiClient espClient;\n")
        sb.append("PubSubClient client(espClient);\n\n")

        sb.append("void callback(char* topic, byte* payload, unsigned int length) {\n")
        sb.append("  String msg = \"\";\n")
        sb.append("  for (int i = 0; i < length; i++) { msg += (char)payload[i]; }\n")
        sb.append("  String t = String(topic);\n\n")

        widgets.filter { it.type != WidgetType.SENSOR_GAUGE }.forEach { w ->
            val safeName = w.title.uppercase().replace(" ", "_").replace("[^A-Z0-9_]".toRegex(), "")
            if (w.type == WidgetType.SWITCH_RELAY || w.type == WidgetType.PUSH_BUTTON) {
                sb.append("  if (t == \"${w.topic}\") {\n")
                sb.append("    digitalWrite(PIN_$safeName, (msg == \"1\" || msg == \"ON\") ? HIGH : LOW);\n")
                sb.append("  }\n")
            } else if (w.type == WidgetType.PWM_SLIDER) {
                sb.append("  if (t == \"${w.topic}\") {\n")
                sb.append("    analogWrite(PIN_$safeName, msg.toInt());\n")
                sb.append("  }\n")
            }
        }
        sb.append("}\n\n")

        sb.append("void setup() {\n")
        sb.append("  Serial.begin(115200);\n")
        widgets.forEach { w ->
            val safeName = w.title.uppercase().replace(" ", "_").replace("[^A-Z0-9_]".toRegex(), "")
            val mode = if (w.type == WidgetType.SENSOR_GAUGE) "INPUT" else "OUTPUT"
            sb.append("  pinMode(PIN_$safeName, $mode);\n")
        }
        sb.append("  WiFi.begin(ssid, password);\n")
        sb.append("  while (WiFi.status() != WL_CONNECTED) { delay(500); }\n")
        sb.append("  client.setServer(mqtt_server, mqtt_port);\n")
        sb.append("  client.setCallback(callback);\n")
        sb.append("}\n\n")

        sb.append("void loop() {\n")
        sb.append("  if (!client.connected()) {\n")
        sb.append("    if (client.connect(\"ESP32_BambuNode\")) {\n")
        widgets.filter { it.type != WidgetType.SENSOR_GAUGE }.forEach { w ->
            sb.append("      client.subscribe(\"${w.topic}\");\n")
        }
        sb.append("    }\n")
        sb.append("  }\n")
        sb.append("  client.loop();\n")
        sb.append("}\n")
        return sb.toString()
    }
}